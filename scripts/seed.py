#!/usr/bin/env python3
"""Turns data/listings.csv (a deliberately messy export) into db/seed.sql.

Real listing data never arrives clean: duplicated rows, "$68" next to "75.00",
tags in random case. This script normalizes all of it, rejects rows that are
missing required fields, and writes deterministic SQL so the same input always
produces the same database.

Usage: python scripts/seed.py
"""
import csv
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "listings.csv"
OUT_PATH = ROOT / "db" / "seed.sql"

CANONICAL_VIBES = {
    "surf", "yoga", "kite", "wellness", "boat-trip", "slow-living",
    "adventure", "food", "community", "outdoors",
}
# Common variants seen in exports map onto the canonical set.
VIBE_ALIASES = {"boattrip": "boat-trip", "boat trip": "boat-trip", "slowliving": "slow-living",
                "slow living": "slow-living"}


def parse_price_cents(raw: str):
    """'$68' | '75.00' | ' 54 ' -> integer cents, or None when unparseable."""
    cleaned = raw.strip().lstrip("$").replace(",", "")
    if not cleaned:
        return None
    try:
        value = round(float(cleaned) * 100)
    except ValueError:
        return None
    return value if value > 0 else None


def normalize_vibes(raw: str):
    out = []
    for token in raw.split("|"):
        tag = token.strip().lower()
        tag = VIBE_ALIASES.get(tag, tag)
        if tag in CANONICAL_VIBES and tag not in out:
            out.append(tag)
    return out


def sql_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def demo_key(host_name: str, place: str) -> str:
    """Stable, unguessable-enough dashboard key for seed hosts (demo only)."""
    digest = hashlib.sha256(f"swellbook-demo:{host_name}:{place}".encode()).hexdigest()[:12]
    return f"demo-{host_name.lower()}-{digest}"


def main() -> int:
    rows_in, dropped, seen = 0, [], set()
    clean = []

    with CSV_PATH.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows_in += 1
            key = (row["name"].strip().lower(), row["place"].strip().lower())
            if key in seen:
                dropped.append(f"duplicate: {row['name'].strip()}")
                continue

            price = parse_price_cents(row["price_per_night"])
            vibes = normalize_vibes(row["vibe_tags"])
            required = [row["host_name"].strip(), row["name"].strip(), row["place"].strip(),
                        row["country"].strip(), row["story"].strip()]
            if price is None or not vibes or not all(required):
                dropped.append(f"rejected (missing price, vibes or fields): {row['name'].strip()}")
                continue

            seen.add(key)
            clean.append({
                "host_name": row["host_name"].strip(),
                "host_story": row["host_story"].strip(),
                "name": row["name"].strip(),
                "place": row["place"].strip(),
                "country": row["country"].strip(),
                "vibes": vibes,
                "price_cents": price,
                "capacity": max(1, int(row["capacity"] or 1)),
                "story": row["story"].strip(),
                "hue": int(row["hue"] or 200) % 360,
                "cover": (row.get("cover") or "").strip(),
            })

    lines = [
        "-- Generated by scripts/seed.py from data/listings.csv. Do not edit by hand.",
        "BEGIN;",
    ]
    for item in clean:
        slug_source = f"{item['name']}-{item['place'].split(',')[0]}"
        slug = "".join(ch if ch.isalnum() else "-" for ch in slug_source.lower())
        slug = "-".join(filter(None, slug.split("-")))[:60]
        vibe_array = "ARRAY[" + ",".join(sql_quote(v) for v in item["vibes"]) + "]::text[]"
        cover_sql = sql_quote(item["cover"]) if item["cover"] else "NULL"
        lines.append(
            "WITH host_row AS (INSERT INTO hosts (name, story, dashboard_key) VALUES ("
            f"{sql_quote(item['host_name'])}, {sql_quote(item['host_story'])}, "
            f"{sql_quote(demo_key(item['host_name'], item['place']))}) RETURNING id)\n"
            "INSERT INTO listings (host_id, slug, name, place, country, vibe_tags, "
            "price_per_night_cents, capacity, story, host_story, hue, cover_url)\n"
            f"SELECT id, {sql_quote(slug)}, {sql_quote(item['name'])}, {sql_quote(item['place'])}, "
            f"{sql_quote(item['country'])}, {vibe_array}, {item['price_cents']}, {item['capacity']}, "
            f"{sql_quote(item['story'])}, {sql_quote(item['host_story'])}, {item['hue']}, {cover_sql} FROM host_row;"
        )
    lines.append("COMMIT;")
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"{rows_in} rows in -> {len(clean)} listings out")
    for reason in dropped:
        print(f"  dropped {reason}")
    print(f"wrote {OUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
